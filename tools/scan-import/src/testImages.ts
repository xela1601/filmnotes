/**
 * Minimal, valid image byte streams for the tests.
 *
 * Real sample images are deliberately not committed: the import only cares about the file
 * extension and the bytes it forwards, so a handful of magic bytes is enough and keeps the
 * repository free of binary fixtures.
 */

